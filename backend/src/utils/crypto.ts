import crypto from 'crypto';
import dotenv from 'dotenv';

dotenv.config();

function getKey(): Buffer {
  const rawKey = process.env.ENCRYPTION_KEY || 'emergency-qr-medical-response-secure-key-2026';
  return crypto.createHash('sha256').update(rawKey).digest();
}

const IV_LENGTH = 16;

/**
 * Encrypts an internal identifier or data string using AES-256-CBC.
 * Output format: [16-byte IV in hex]:[ciphertext in hex]
 */
export function encryptId(text: string): string {
  if (!text || typeof text !== 'string') {
    throw new Error('Text to encrypt must be a non-empty string');
  }

  const iv = crypto.randomBytes(IV_LENGTH);
  const cipher = crypto.createCipheriv('aes-256-cbc', getKey(), iv);
  let encrypted = cipher.update(text, 'utf8');
  encrypted = Buffer.concat([encrypted, cipher.final()]);
  return `${iv.toString('hex')}:${encrypted.toString('hex')}`;
}

/**
 * Decrypts a token generated by encryptId.
 * Validates the hex strings and IV length.
 */
export function decryptId(token: string): string {
  if (!token || typeof token !== 'string') {
    throw new Error('Invalid token provided');
  }

  const parts = token.split(':');
  if (parts.length !== 2) {
    throw new Error('Invalid token format');
  }

  const [ivHex, encryptedHex] = parts;
  if (!ivHex || !encryptedHex) {
    throw new Error('Malformed token parts');
  }

  const iv = Buffer.from(ivHex, 'hex');
  if (iv.length !== IV_LENGTH) {
    throw new Error('Invalid initialization vector length');
  }

  const encryptedText = Buffer.from(encryptedHex, 'hex');
  const decipher = crypto.createDecipheriv('aes-256-cbc', getKey(), iv);
  let decrypted = decipher.update(encryptedText);
  decrypted = Buffer.concat([decrypted, decipher.final()]);
  return decrypted.toString('utf8');
}

/**
 * Quick validation check for token format
 */
export function isValidToken(token: string): boolean {
  try {
    const parts = token.split(':');
    return parts.length === 2 && parts[0].length === IV_LENGTH * 2 && parts[1].length > 0;
  } catch {
    return false;
  }
}
